"""Create fixed synthetic typography probes and one real, manually transcribed crop."""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "ocr"
OUT.mkdir(exist_ok=True)
font = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 76)
fixtures = [
    ("synthetic_directory", "ELEVATORS LEFT\nLEVEL 2\nROOMS 201 TO 214"),
    ("synthetic_exit", "EXIT\nPLEASE KEEP DOOR CLOSED"),
    ("synthetic_label", "OAT DRINK\nPRICE $4.50\nBEST BEFORE 2027-01-15"),
]
rows = []
for identifier, text in fixtures:
    image = Image.new("RGB", (1440, 600), "white")
    draw = ImageDraw.Draw(image)
    draw.multiline_text((60, 65), text, font=font, fill="black", spacing=35)
    path = OUT / f"{identifier}.png"
    image.save(path)
    rows.append({"id": identifier, "path": str(path.resolve()), "reference": text,
                 "provenance": "SYNTHETIC: rendered Arial typography, generated by prepare_ocr.py, no real-camera claim"})
# Ground truth manually transcribed from the visible van before running OCR.
source = ROOT / "data/images/000000184324.jpg"
path = OUT / "real_police_van_crop.png"
Image.open(source).crop((121, 223, 156, 242)).resize((280, 152), Image.Resampling.BICUBIC).save(path)
rows.append({"id": "real_police_van_crop", "path": str(path.resolve()), "reference": "POLICE",
             "provenance": "REAL COCO val2017 image 184324, CC BY 2.0 per COCO metadata, source and SHA256 in data/manifest.json. Manually selected crop (121,223,156,242), resized 8x bicubic. Single tiny word; not a representative OCR benchmark."})
(OUT / "references.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
print(f"Prepared {len(rows)} fixed OCR fixtures")
